"""Booktabs LaTeX tables for D138 Steps 2-4 (python -m bgm.analysis.d138_tables -> results/tables.tex).

Reads the CSVs the step scripts write (results/d138_hubness/summary.csv, results/d138_regularisation/single_heads.csv,
results/d138_candidates/ablation.csv); a missing CSV skips its table.
"""
from __future__ import annotations

import logging
from pathlib import Path

import numpy as np

log = logging.getLogger(__name__)

OUT = Path("results/tables.tex")


def esc(s: str) -> str:
    return (str(s).replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").replace("τ", r"$\tau$")
            .replace("σ", r"$\sigma$").replace("β", r"$\beta$").replace("−", "--").replace("×", r"$\times$"))


def pm(m: float, s: float, nd: int = 3) -> str:
    return f"{m:.{nd}f} $\\pm$ {s:.{nd}f}"


def ci(d: float, lo: float, hi: float) -> str:
    if not np.isfinite(d):
        return "--"
    sig = "$^\\ast$" if lo > 0 or hi < 0 else ""
    return f"{d:+.3f} [{lo:+.3f}, {hi:+.3f}]{sig}"


def hubness_table(pd) -> list[str]:
    p = Path("results/d138_hubness/summary.csv")
    if not p.exists():
        return []
    df = pd.read_csv(p)
    L = [r"\begin{table}[t]", r"\centering", r"\small", r"\setlength{\tabcolsep}{4pt}",
         r"\caption{Test-time hubness reduction on the 10-head ensemble's track scores (no retraining; parameters tuned on validation; 5 folds $\times$ 3 ensembles; $\Delta$ with 95\% film-group bootstrap CI, $^\ast$ = CI excludes 0).}",
         r"\label{tab:hubness}", r"\begin{tabular}{lcccc}", r"\toprule",
         r"Scoring & R@1 & R@10 & MedR & $\Delta$R@10 \\", r"\midrule"]
    for _, r in df.iterrows():
        L.append(f"{esc(r.system)} & {pm(r['R@1_mean'], r['R@1_std'])} & {pm(r['R@10_mean'], r['R@10_std'])} & "
                 f"{pm(r['MedR_mean'], r['MedR_std'], 1)} & {ci(r['dR@10'], r['dR@10_lo'], r['dR@10_hi'])} \\\\")
    return L + [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]


def reg_table(pd) -> list[str]:
    p = Path("results/d138_regularisation/single_heads.csv")
    if not p.exists():
        return []
    df = pd.read_csv(p)
    L = [r"\begin{table}[t]", r"\centering", r"\small", r"\setlength{\tabcolsep}{4pt}",
         r"\caption{Regularisation of the projection heads, one change at a time (single heads, 5 folds $\times$ 3 seeds; train/test = track R@10, val = segment R@10 used for selection; $\Delta$ test R@10 vs baseline with 95\% film-group bootstrap CI).}",
         r"\label{tab:regularisation}", r"\begin{tabular}{lccccc}", r"\toprule",
         r"Setting & Train R@10 & Val R@10 & Test R@10 & Gap & $\Delta$ Test R@10 \\", r"\midrule"]
    for _, r in df.iterrows():
        d = ci(r.get("dtest_R@10", np.nan), r.get("dtest_R@10_lo", np.nan), r.get("dtest_R@10_hi", np.nan))
        L.append(f"{esc(r.setting)} & {pm(r['train_R@10'], r['train_R@10_std'])} & {r['val_segR@10']:.3f} & "
                 f"{pm(r['test_R@10'], r['test_R@10_std'])} & {r.gap_train_test:.3f} & {d} \\\\")
    return L + [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]


def cand_table(pd) -> list[str]:
    p = Path("results/d138_candidates/ablation.csv")
    if not p.exists():
        return []
    df = pd.read_csv(p)
    gt = df.gt_sw_min.iloc[0]
    gts = f"ground truth {gt:.2f}" if np.isfinite(gt) else "ground truth n/a"
    L = [r"\begin{table}[t]", r"\centering", r"\small", r"\setlength{\tabcolsep}{3.5pt}",
         f"\\caption{{Candidate ablation for stitching, one factor at a time around the default (bold); penalties re-tuned on validation per cell; switches/min {gts}; candidate recall = true window ($\\pm$0.5\\,s) among the top $C$, not comparable across window steps.}}",
         r"\label{tab:candidates}", r"\begin{tabular}{lccccccc}", r"\toprule",
         r"Factor & $K$ & $C$ & Step (s) & Switch F1 & Sw./min & Song acc. & Cand. recall \\", r"\midrule"]
    prev = None
    for _, r in df.iterrows():
        if prev is not None and r.factor != prev:
            L.append(r"\midrule")
        prev = r.factor
        cells = [esc(r.factor), f"{r.K}", f"{r.C}", f"{r.step_s:g}", pm(r.switch_f1, r.switch_f1_std), f"{r.sw_min:.2f}",
                 pm(r.song_acc, r.song_acc_std), f"{r.cand_recall:.3f}"]
        if r.shipped:
            cells = [f"\\textbf{{{c}}}" for c in cells]
        L.append(" & ".join(cells) + r" \\")
    return L + [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]


def main() -> None:
    import pandas as pd
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    L = ["% D138 tables (generated by python -m bgm.analysis.d138_tables). Needs \\usepackage{booktabs}.", ""]
    for f in (hubness_table, reg_table, cand_table):
        L += f(pd)
    OUT.write_text("\n".join(L) + "\n")
    log.info("wrote %s", OUT)


if __name__ == "__main__":
    main()
