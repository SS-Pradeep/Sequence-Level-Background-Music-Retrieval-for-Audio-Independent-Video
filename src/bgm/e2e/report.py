"""D141 report: end-to-end soundtrack model vs the shipped decoder, cleaned title split (5 folds x 3 ensembles).

Per test sequence the metric is averaged over a fold's 3 ensembles; CIs and paired differences use a bootstrap over
sequences (each concatenation / in-film sequence is one cluster; in-film boundary F1 is micro-pooled, so its CI
resamples sequences and recomputes the pooled F1). Mean ± std over the 15 runs.

Run: python -m bgm.e2e.report   -> results/cleaned/e2e_soundtrack.{md,csv}
"""
from __future__ import annotations

import json
import logging
from pathlib import Path

import numpy as np
import pandas as pd
import torch

from bgm.e2e.bounds import MUSIC_NAMES, N_MUSIC_MAIN
from bgm.eval.metrics import cluster_bootstrap

log = logging.getLogger(__name__)
ROOT = Path("runs/cleaned/e2e")
OUT = Path("results/cleaned/e2e_soundtrack")
B = 10000
FOLDS, ENS = range(5), range(3)
LABEL = {"fixed": "shipped: fixed penalties (stitch.json)", "trans": "transitions + emission scale (heads frozen)",
         "joint_v": "joint: heads + video-only transitions", "joint": "**joint: heads + video and music transitions**",
         "joint_nodur": "joint without segment durations (shortcut check)",
         "joint_edge": "joint + file-edge music features (leak upper bound, not a system)"}
ORDER = ("fixed", "trans", "joint_v", "joint", "joint_nodur", "joint_edge")


def load(variant: str) -> dict | None:
    runs = {}
    for k in FOLDS:
        for e in ENS:
            p = ROOT / variant / f"fold{k}" / f"seed{e}" / "perseq.npz"
            if not p.exists():
                return None
            with np.load(p) as z:
                runs[(k, e)] = {key: z[key] for key in z.files}
            runs[(k, e)]["_metrics"] = json.loads((p.parent / "metrics.json").read_text())
    return runs


def per_seq(runs: dict, key: str) -> np.ndarray:
    """[n_sequences] the metric averaged over each fold's ensembles, folds concatenated."""
    return np.concatenate([np.mean([runs[(k, e)][key] for e in ENS], 0) for k in FOLDS])


def per_run(runs: dict, key: str) -> np.ndarray:
    return np.array([np.mean(runs[(k, e)][key]) for k in FOLDS for e in ENS])


def micro_f1(tp, fp, fn) -> float:
    d = 2 * tp + fp + fn
    return float(2 * tp / d) if d else float("nan")


def f1_runs(runs: dict, lat: str) -> np.ndarray:
    return np.array([micro_f1(*(runs[(k, e)][f"{lat}/infilm/infilm_{c}"].sum() for c in ("tp", "fp", "fn"))) for k in FOLDS for e in ENS])


def f1_boot(runs: dict, lat: str, base: dict | None = None, base_lat: str = "A", seed: int = 0) -> dict:
    """Pooled in-film F1 (counts summed over ensembles) with a sequence bootstrap; with base, the paired difference."""
    def counts(r, l):
        return np.stack([per_seq(r, f"{l}/infilm/infilm_{c}") for c in ("tp", "fp", "fn")], 1)
    c = counts(runs, lat)
    cb = counts(base, base_lat) if base is not None else None
    f = lambda x: micro_f1(*x.sum(0))  # noqa: E731
    rng = np.random.default_rng(seed)
    n = len(c)
    draws = rng.integers(0, n, (B, n))
    vals = np.array([f(c[d]) - (f(cb[d]) if cb is not None else 0.0) for d in draws])
    m = f(c) - (f(cb) if cb is not None else 0.0)
    return {"mean": m, "lo": float(np.nanquantile(vals, 0.025)), "hi": float(np.nanquantile(vals, 0.975))}


def _ci(c: dict, d: int = 3, sign: bool = False) -> str:
    fmt = f"{{:+.{d}f}}" if sign else f"{{:.{d}f}}"
    star = "*" if sign and (c["lo"] > 0 or c["hi"] < 0) else ""
    return f"{fmt.format(c['mean'])} [{fmt.format(c['lo'])}, {fmt.format(c['hi'])}]{star}"


def _ms(v: np.ndarray, d: int = 3) -> str:
    return f"{np.mean(v):.{d}f} ± {np.std(v, ddof=1):.{d}f}"


def main() -> Path:
    runs = {v: load(v) for v in ORDER}
    runs = {v: r for v, r in runs.items() if r is not None}
    assert "fixed" in runs, "the fixed baseline is missing"
    base = runs["fixed"]
    n_cat = len(per_seq(base, "A/test/part_acc"))
    n_inf = len(per_seq(base, "A/infilm/part_acc"))
    rows, L = [], ["# End-to-end soundtrack retrieval: heads, emission and cross-modal transitions trained together (D141)", "",
                   "Generated by `python -m bgm.e2e.report` (src/bgm/e2e/). Cleaned title split, 5 folds × 3 disjoint 10-head ensembles "
                   f"(15 runs per row). Test sets: the frozen concatenations (concat_sets_title.json, {n_cat} sequences, as tune-stitch) "
                   f"and the frozen in-film blocked sequences (cue_sequences_title.json, {n_inf}). Every learned row starts from the "
                   "shipped decoder (epoch 0 reproduces stitch.json's val objective) and keeps the best val epoch (val concatenations, "
                   "part track accuracy + switch F1). Mean ± std over runs; [CI] / Δ: bootstrap over sequences (10,000), per-sequence "
                   "values averaged over a fold's 3 ensembles; Δ paired against the shipped decoder; * = CI excludes 0.", "",
                   "**Lattices.** A = the shipped candidate lattices (same windows for every row; only scores and transitions change). "
                   "B = lattices rebuilt by the full pipeline (coarse shortlist, sliding windows, top J) with the fine-tuned heads, "
                   "so better heads can also bring the right song INTO the lattice.", ""]
    for lat, title in (("A", "Shipped lattices (A)"), ("B", "Lattices rebuilt with the fine-tuned heads (B)")):
        have = [v for v in ORDER if v in runs and (lat == "A" or f"B/test/part_acc" in runs[v][(0, 0)])]
        if not have:
            continue
        L += [f"## {title}", "", "### Concatenations (clip joins = true switches)", "",
              "| system | part track acc | switch F1 ±1 s | switches/min (truth) | song in lattice | Δ part acc | Δ switch F1 |",
              "|---|---|---|---|---|---|---|"]
        for v in have:
            r = runs[v]
            pa, sf = per_seq(r, f"{lat}/test/part_acc"), per_seq(r, f"{lat}/test/switch_f1")
            bpa, bsf = per_seq(base, "A/test/part_acc"), per_seq(base, "A/test/switch_f1")
            cl = np.arange(len(pa))
            d1 = "—" if v == "fixed" and lat == "A" else _ci(cluster_bootstrap(pa - bpa, cl, B), sign=True)
            d2 = "—" if v == "fixed" and lat == "A" else _ci(cluster_bootstrap(sf - bsf, cl, B), sign=True)
            L.append(f"| {LABEL[v]} | {_ms(per_run(r, f'{lat}/test/part_acc'))} | {_ms(per_run(r, f'{lat}/test/switch_f1'))} | "
                     f"{np.mean(per_run(r, f'{lat}/test/switches_per_min')):.2f} ({np.mean(per_run(r, f'{lat}/test/true_per_min')):.2f}) | "
                     f"{np.mean(per_run(r, f'{lat}/test/gold_track_in_lattice')):.3f} | {d1} | {d2} |")
            rows.append({"lattice": lat, "set": "concat", "variant": v, "part_acc": float(pa.mean()), "switch_f1": float(sf.mean()),
                         "d_part_acc": float((pa - bpa).mean()), "d_switch_f1": float((sf - bsf).mean())})
        L += ["", "### In-film blocked sequences (true switches = cue changes inside one film)", "",
              "| system | part track acc | in-film boundary F1 ±1 s [CI] | switches/min (truth) | Δ part acc | Δ in-film F1 |", "|---|---|---|---|---|---|"]
        for v in have:
            r = runs[v]
            pa, bpa = per_seq(r, f"{lat}/infilm/part_acc"), per_seq(base, "A/infilm/part_acc")
            cl = np.arange(len(pa))
            same = v == "fixed" and lat == "A"
            L.append(f"| {LABEL[v]} | {_ms(per_run(r, f'{lat}/infilm/part_acc'))} | {_ms(f1_runs(r, lat))} {_ci(f1_boot(r, lat))} | "
                     f"{np.mean(per_run(r, f'{lat}/infilm/switches_per_min')):.2f} ({np.mean(per_run(r, f'{lat}/infilm/true_per_min')):.2f}) | "
                     f"{'—' if same else _ci(cluster_bootstrap(pa - bpa, cl, B), sign=True)} | {'—' if same else _ci(f1_boot(r, lat, base), sign=True)} |")
            rows.append({"lattice": lat, "set": "infilm", "variant": v, "part_acc": float(pa.mean()), "infilm_f1": f1_boot(r, lat)["mean"],
                         "d_part_acc": float((pa - bpa).mean()), "d_infilm_f1": f1_boot(r, lat, base)["mean"]})
        L.append("")
    # ---- what was learned
    L += ["## What the transitions learned", "",
          "Music weights act on the switch / jump cost (lower = a better place to leave / enter a piece); the cross-modal part "
          "(U, V) scales them by the video boundary embedding. Mean ± std over the 15 runs of the best epoch.", ""]
    for v in ("joint", "trans", "joint_edge"):
        if v not in runs:
            continue
        P = [runs[v][(k, e)]["_metrics"]["params"] for k in FOLDS for e in ENS]
        nf = len(P[0]["w_out"])
        st = [torch.load(ROOT / v / f"fold{k}" / f"seed{e}" / "transitions.pt", map_location="cpu") for k in FOLDS for e in ENS]
        un = np.array([float(s["U"].norm()) for s in st]), np.array([float(s["V"].norm()) for s in st])
        best = [runs[v][(k, e)]["_metrics"]["best_epoch"] for k in FOLDS for e in ENS]
        L += [f"**{LABEL[v]}**: emission scale a {_ms(np.array([p['a'] for p in P]), 2)}; b_switch {_ms(np.array([p['b_sw'] for p in P]), 2)}; "
              f"b_jump {_ms(np.array([p['b_jp'] for p in P]), 2)}; μ (key/tempo) {_ms(np.array([p['mu'] for p in P]), 3)}; "
              f"|U| {_ms(un[0], 3)}, |V| {_ms(un[1], 3)}; best epoch {np.median(best):.0f} (0 = shipped decoder kept in "
              f"{sum(b == 0 for b in best)} of 15 runs)", "",
              "| music feature | weight at exit (leaving a piece) | weight at entry (starting a piece) |", "|---|---|---|"]
        for j in range(nf):
            wo, wi = np.array([p["w_out"][j] for p in P]), np.array([p["w_in"][j] for p in P])
            L.append(f"| {MUSIC_NAMES[j]}{' (edge, leak)' if j >= N_MUSIC_MAIN else ''} | {_ms(wo)} | {_ms(wi)} |")
        L.append("")
    L += ["Feature directions: beat / downbeat / phrase are distances (0 = on the grid), so a POSITIVE weight means "
          "\"cheaper to cut on the grid\"; novelty / onset / rms are within-file ranks.", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows).to_csv(OUT.with_suffix(".csv"), index=False)
    OUT.with_suffix(".md").write_text("\n".join(L) + "\n")
    log.info("wrote %s", OUT.with_suffix(".md"))
    return OUT.with_suffix(".md")


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    print(main())
